window.addEventListener("storage", (event) => {
  if (event.key !== STORAGE_KEY) {
    return;
  }
  preference = readPreference();
  resolved = preference === "auto" ? resolveAuto() : preference;
  notify();
});
window.addEventListener("languagechange", () => {
  if (preference !== "auto") {
    return;
  }
  const next = resolveAuto();
  if (next === resolved) {
    return;
  }
  resolved = next;
  notify();
});
