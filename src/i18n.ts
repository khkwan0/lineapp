const STORAGE_KEY = "lineapp.language";
const listeners = new Set<() => void>();

function matchLocale(language: string): LocaleId | null {
  const lower = language.toLowerCase();
  if (lower.startsWith("zh")) {
    return /hant|tw|hk|mo/.test(lower) ? "zh-Hant" : "zh-Hans";
  }
  const base = lower.split("-")[0] === "in" ? "id" : lower.split("-")[0];
  return LOCALES.some((locale) => locale.id === base) ? (base as LocaleId) : null;
}

function resolveAuto(): LocaleId {
  const list = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const language of list) {
    const match = matchLocale(language || "");
    if (match) {
      return match;
    }
  }
  return "en";
}

function readPreference(): "auto" | LocaleId {
  const raw = localStorage.getItem(STORAGE_KEY);
  if (raw === "auto" || LOCALES.some((locale) => locale.id === raw)) {
    return raw as "auto" | LocaleId;
  }
  return "auto";
}

let preference: "auto" | LocaleId = readPreference();
let resolved: LocaleId = preference === "auto" ? resolveAuto() : preference;

function notify(): void {
  applyDocument();
  listeners.forEach((listener) => listener());
}

function applyDocument(): void {
  const locale = LOCALES.find((item) => item.id === resolved) ?? LOCALES[0];
  document.documentElement.lang = locale.tag;
  document.documentElement.dir = locale.dir;
}

export function languagePreference(): "auto" | LocaleId {
  return preference;
}

export function resolvedLanguage(): LocaleId {
  return resolved;
}

export function intlLocale(): string {
  return LOCALES.find((item) => item.id === resolved)?.tag ?? "en";
}

export function languageName(id: "auto" | LocaleId): string {
  if (id === "auto") {
    return t("autoLanguage");
  }
  return LOCALES.find((item) => item.id === id)?.name ?? id;
}

export function setLanguage(next: string): void {
  const value: "auto" | LocaleId = next === "auto" || LOCALES.some((locale) => locale.id === next) ? (next as "auto" | LocaleId) : "auto";
  preference = value;
  localStorage.setItem(STORAGE_KEY, value);
  const active = value === "auto" ? resolveAuto() : value;
  if (active === resolved) {
    notify();
    return;
  }
  resolved = active;
  notify();
}

export function onLocaleChange(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const raw = catalogs[resolved][key] ?? en[key];
  if (!vars) {
    return raw;
  }
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

export function applyI18n(root: ParentNode = document): void {
  applyDocument();
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n as MessageKey;
    if (key in en) {
      element.textContent = t(key);
    }
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder as MessageKey;
    if ((element instanceof HTMLInputElement || element instanceof HTMLTextAreaElement) && key in en) {
      element.placeholder = t(key);
    }
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-aria]").forEach((element) => {
    const key = element.dataset.i18nAria as MessageKey;
    if (key in en) {
      element.setAttribute("aria-label", t(key));
    }
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((element) => {
    const key = element.dataset.i18nTitle as MessageKey;
    if (key in en) {
      element.title = t(key);
    }
  });
}

